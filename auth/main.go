package main

import (
	_ "auth-server/docs" // docs is generated by Swag CLI, you have to import it.
	"fmt"
	"log"
	"os"

	uuid "github.com/satori/go.uuid"
	"github.com/spf13/afero"
	"gorm.io/gorm"
)

const (
	romPath  = "/local_roms/"
	savePath = "/local_saves/"
)

var (
	appFs         afero.Fs
	userdb        *gorm.DB
	accessSignKey []byte
)

func main() {
	log.Println("gbajs3 auth server started")
	var err error
	cfg, logfile, gconf := initRuntime(os.Getenv)
	accessSignKey = uuid.NewV4().Bytes()
	log.SetOutput(logfile)

	userdb, err = newGbaJsDatabase(gconf)
	if err != nil {
		panic(fmt.Errorf("could not connect to gbajs3 db: %w", err))
	}

	appFs = afero.NewBasePathFs(afero.NewOsFs(), cfg.basePath)

	serveRequests(":443", cfg.certLoc, cfg.keyLoc, cfg.clientHost)
}
